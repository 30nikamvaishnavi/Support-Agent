const a = require("./app.js");
const assert = require("assert");
assert.strictEqual(a.formatMetric("overall_pass_rate", 0.8333), "83.3%");
assert.strictEqual(a.formatMetric("overall_pass_rate", 1), "100%");
assert.strictEqual(a.formatMetric("grounding_fallback_rate", null), "n/a");
assert.strictEqual(a.formatMetric("avg_latency_ms", 1234), "1.23 s");
assert.strictEqual(a.formatMetric("p95_latency_ms", 0.9), "0.9 ms");
assert.strictEqual(a.categoryOf("adv-03"), "adv");
assert.deepStrictEqual(a.parseProgress(["x", "[3/30] ord-01: PASS", "y"]), { done: 3, total: 30 });
assert.strictEqual(a.parseProgress(["nothing"]), null);
let s = a.traceSteps({ intent: "blocked", tool_called: "none", response_source: "template", latency_ms: 0.2, api_calls: 0, engine: "sequential" });
assert.strictEqual(s[0].status, "bad"); assert.strictEqual(s[1].status, "skip"); assert.strictEqual(s[2].status, "skip");
s = a.traceSteps({ intent: "refund_request", sentiment: "calm", confidence: 0.9, tool_called: "create_ticket", tool_status: "ticket_created", response_source: "llm", latency_ms: 1500, api_calls: 2, engine: "langgraph" });
assert.strictEqual(s[1].status, "ok"); assert.strictEqual(s[2].status, "ok"); assert.strictEqual(s[3].status, "ok");
assert.ok(s[3].chips.some((c) => c.text === "1.50 s")); assert.ok(s[3].chips.some((c) => c.text === "2 API calls"));
s = a.traceSteps({ intent: "faq", confidence: 0.3, sentiment: "calm", tool_called: "human_handoff", response_source: "template_grounding_fallback" });
assert.strictEqual(s[1].status, "warn"); assert.strictEqual(s[2].status, "warn"); assert.strictEqual(s[3].status, "warn");
assert.strictEqual(a.traceSteps({ intent: "error", tool_called: "human_handoff", response_source: "template" })[1].status, "bad");
assert.ok(a.SCENARIOS.length >= 8);
console.log("JS helper tests passed");
